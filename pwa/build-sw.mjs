#!/usr/bin/env node
/**
 * 生成 dist/sw.js（Service Worker）
 *
 * 为什么需要这一步：首屏要能"打开就有"，SW 必须**安装时**就把
 * index.html + 主包 js + 首屏 css 全部缓存下来，而不能等首次请求再顺手缓存。
 * 这些文件名里带 contenthash，构建后才知道，所以只能构建末尾生成。
 *
 * 用法：node pwa/build-sw.mjs   （pnpm build 会自动调用）
 * 输入：dist/index.html、dist/manifest.webmanifest、dist/static/**
 * 输出：dist/sw.js（版本号 = 预缓存清单 + html 内容的哈希）
 */
import { createHash } from 'node:crypto'
import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = resolve(fileURLToPath(new URL('.', import.meta.url)))
const dist = resolve(here, '..', 'dist')
const templatePath = join(here, 'sw.js')

const fail = (message) => {
  console.error(`[build-sw] ${message}`)
  process.exit(1)
}

const indexPath = join(dist, 'index.html')
const html = (() => {
  try {
    return readFileSync(indexPath, 'utf8')
  } catch {
    fail(`找不到 ${indexPath}：先执行 pnpm build（本脚本在构建末尾运行）`)
  }
})()

/** 从 index.html 取出构建产物（main.*.js / main.*.css） */
const assets = [...html.matchAll(/(?:src|href)="(static\/[^"]+)"/g)].map((match) => match[1])
if (assets.length === 0) {
  fail('index.html 里没有找到 static/ 资源（html 插件没生效？）')
}

/** 从 manifest 取图标，避免两处各维护一份清单 */
const icons = (() => {
  const manifestPath = join(dist, 'manifest.webmanifest')
  try {
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
    return (manifest.icons ?? []).map((icon) => String(icon.src))
  } catch {
    fail(`读取 ${manifestPath} 失败：manifest 缺失或不是合法 JSON`)
  }
})()

// 顺序无关紧要，但保持稳定：固定用排序后的清单算版本号
const files = [...new Set(['index.html', 'manifest.webmanifest', ...icons, ...assets])].sort()
const template = readFileSync(templatePath, 'utf8')

/** 版本号：预缓存清单 + 大小 + html + sw 模板本身，任一变化就是一个新版本 */
const fingerprint = createHash('sha256')
for (const file of files) {
  let size = 0
  try {
    size = statSync(join(dist, file)).size
  } catch {
    fail(`index.html/manifest 引用了不存在的文件：${file}`)
  }
  fingerprint.update(`${file}:${size}\n`)
}
fingerprint.update(html)
fingerprint.update(template)
const version = fingerprint.digest('hex').slice(0, 12)

const precache = ['./', './index.html', ...files.filter((file) => !file.endsWith('index.html')).map((file) => `./${file}`)]

// 占位符必须恰好出现一次：注释里顺手提一嘴就会把 JSON 注进注释里（真踩过）
const occurrences = (text, part) => text.split(part).length - 1
for (const [placeholder, expected] of [
  ["'__SW_VERSION__'", 1],
  ['__SW_PRECACHE__', 1],
]) {
  const found = occurrences(template, placeholder)
  if (found !== expected) {
    fail(
      `模板 pwa/sw.js 里 ${placeholder} 出现了 ${found} 次（应为 ${expected} 次）：` +
        '注释中都不要再写这个字面量，否则替换会落到注释上'
    )
  }
}

const output = template
  .replace("'__SW_VERSION__'", `'${version}'`)
  .replace('__SW_PRECACHE__', JSON.stringify(precache, null, 2))

if (output.includes('__SW_')) {
  fail('生成结果里仍然残留占位符，检查 pwa/sw.js 与 pwa/build-sw.mjs')
}

writeFileSync(
  join(dist, 'sw.js'),
  `/* generated by pwa/build-sw.mjs —— 不要直接改这个文件，改 pwa/sw.js */\n${output}`
)

console.log(`[build-sw] dist/sw.js v${version}：预缓存 ${precache.length} 个文件`)
console.log(`[build-sw]   ${precache.join('\n[build-sw]   ')}`)
